from typing import Protocol

from sentinel.stream.domain import OrderEvent, ProducerConfiguration, StreamRecord


class EventRepository(Protocol):
    def initialize(self) -> None: ...

    def configuration(self) -> ProducerConfiguration: ...

    def store(self, records: list[StreamRecord]) -> None: ...


class EventStream(Protocol):
    def open(self) -> None: ...

    def publish(self, events: list[OrderEvent]) -> None: ...

    def receive(self) -> list[StreamRecord]: ...

    def acknowledge(self, records: list[StreamRecord]) -> None: ...

    def close(self) -> None: ...
